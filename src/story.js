export const BEFORE_DAYS = 90 // 退休到倒下
export const FOUND_DAY = 90 // 倒下後第幾天被發現
export const LISTING_DAY = FOUND_DAY + 47 // 遊戲開場

// 那一天＝9 月 15 日，星期二。年份只用來算星期幾，不會顯示。
const DAY_ZERO = new Date(2026, 8, 15)

export function dateOf(day) {
  const d = new Date(DAY_ZERO)
  d.setDate(d.getDate() + Math.round(day))
  return {
    month: d.getMonth() + 1,
    date: d.getDate(),
    weekday: '日一二三四五六'[d.getDay()],
    weekend: d.getDay() === 0 || d.getDay() === 6,
  }
}

// 每個標籤都講清楚是從哪裡起算，不會只寫「第幾天」
export function relLabel(day, aliveLine = false) {
  const d = Math.round(day)
  if (d > FOUND_DAY) return `被發現後第 ${d - FOUND_DAY} 天`
  if (d > 0) return aliveLine ? `那一晚之後第 ${d} 天` : `倒下後第 ${d} 天`
  if (d === 0) return '那一天'
  return `倒下前 ${-d} 天`
}

